# ④ XGBoost               : 나무들이 서로의 실수를 순차적으로 보완하며 학습
#
# ※ 나이브 모형이 왜 필요할까요?
#   아무리 복잡한 AI라도, "그냥 지난 값을 그대로 베끼는 것"보다 못하다면
#   그 AI는 쓸모가 없는 거예요. 그래서 나이브 모형은 "이 정도는 이겨야
#   진짜 실력 있는 모형이다"라는 최소 기준선(baseline) 역할을 해요.
