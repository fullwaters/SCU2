# %%
# ------------------------------------------------------------
# [셀 3] 파일 업로드 및 데이터 확인
# ------------------------------------------------------------
# '기준금리', 'CD금리', '회사채금리' 열이 포함된 주별 시계열 CSV를 올려주세요.

uploaded = files.upload()
# 위 줄: 마우스로 CSV 파일을 클릭해서 업로드하세요!

file_name = list(uploaded.keys())[0]
# 위 줄: 업로드한 파일의 이름을 자동으로 찾아줘요.

df = pd.read_csv(file_name)
# 위 줄: CSV 파일을 표(데이터프레임) 형태로 읽어와요.

print("파일 업로드 완료! 데이터 미리보기:")
# 위 줄: 안내 메시지예요.

print(df.head())
# 위 줄: 데이터의 맨 위 5줄을 살짝 보여줘요.


# %%
# ------------------------------------------------------------
# [셀 4] 빈칸(결측치) 자동으로 채우기
# ------------------------------------------------------------

df = df.fillna(method='ffill')
# 위 줄: 빈칸을 "바로 앞의 값"으로 채워요.

df = df.fillna(method='bfill')
# 위 줄: 맨 앞부분에 남은 빈칸은 "뒤의 값"으로 채워요.

print("빈칸 채우기 완료! 남은 빈칸 개수:")
# 위 줄: 안내 메시지예요.

print(df.isnull().sum())
# 위 줄: 각 열에 빈칸이 몇 개 남았는지 확인해요.


# %%
# ------------------------------------------------------------
# [셀 5] 특징(Feature) 만들기 - 5.2 설계안 그대로 적용
# ------------------------------------------------------------
# X(입력변수) = 기준금리, CD금리, 회사채금리, CD-기준금리 스프레드,
#              회사채-CD 스프레드, 1주 변화율, 4주 변동성
# y(목표변수) = 다음 주(1주 뒤) 회사채금리

df['CD_기준금리_스프레드'] = df['CD금리'] - df['기준금리']
# 위 줄: CD금리에서 기준금리를 뺀 스프레드를 계산해요.

df['회사채_CD_스프레드'] = df['회사채금리'] - df['CD금리']
# 위 줄: 회사채금리에서 CD금리를 뺀 스프레드를 계산해요.

df['1주_변화율'] = df['회사채금리'].pct_change()
# 위 줄: 회사채금리가 지난주 대비 몇 % 변했는지(변화율)를 계산해요.

df['4주_변동성'] = df['회사채금리'].rolling(window=4).std()
# 위 줄: 최근 4주 동안 회사채금리가 얼마나 출렁였는지(표준편차)를 계산해요.

df['y_다음주_회사채금리'] = df['회사채금리'].shift(-1)
# 위 줄: 한 행씩 위로 당겨서, "다음 주" 회사채금리를 이번 주 행에 붙여줘요.
#       이렇게 하면 "이번 주 정보(X) -> 다음 주 결과(y)" 짝이 완성돼요.

df = df.dropna().reset_index(drop=True)
# 위 줄: 변화율·변동성·shift 계산 과정에서 생긴 빈 줄(맨 앞/맨 뒤)을 제거해요.

print("특징(Feature) 생성 완료! 데이터 미리보기:")
# 위 줄: 안내 메시지예요.

print(df.head())
# 위 줄: 완성된 데이터의 앞부분을 확인해요.


# %%
# ------------------------------------------------------------
# [셀 6] X, y 나누고 시간순으로 학습/시험 데이터 분할하기 (80:20)
# ------------------------------------------------------------

feature_cols = ['기준금리', 'CD금리', '회사채금리', 'CD_기준금리_스프레드',
                 '회사채_CD_스프레드', '1주_변화율', '4주_변동성']
# 위 줄: 입력변수(X)로 쓸 7개 열의 이름을 정리해요.

X = df[feature_cols]
# 위 줄: 입력변수 X를 만들어요.

y = df['y_다음주_회사채금리']
# 위 줄: 목표변수 y(다음 주 회사채금리)를 만들어요.

split_idx = int(len(df) * 0.8)
# 위 줄: 전체 데이터의 80% 지점이 몇 번째 행인지 계산해요.

X_train, X_test = X.iloc[:split_idx], X.iloc[split_idx:]
# 위 줄: 시간 순서대로 앞 80%는 학습용, 뒤 20%는 시험용으로 나눠요.
#       (무작위로 섞지 않아요! 미래 데이터가 학습에 섞여 들어가는 걸 막기 위해서예요)

y_train, y_test = y.iloc[:split_idx], y.iloc[split_idx:]
# 위 줄: y도 같은 기준으로 나눠요.

print(f"전체 데이터: {len(df)}개  /  학습용: {len(X_train)}개  /  시험용: {len(X_test)}개")
# 위 줄: 데이터가 잘 나뉘었는지 개수를 확인해요.


# %%
# ------------------------------------------------------------
# [셀 7] ① 나이브(Naive) 모형 - 최소 기준선
# ------------------------------------------------------------
# 규칙: "다음 주 회사채금리는 이번 주 회사채금리와 같을 것이다"
# AI를 전혀 쓰지 않는, 가장 단순한 예측 방법이에요.

y_pred_naive = X_test['회사채금리'].values
# 위 줄: 시험 기간 동안, "이번 주 회사채금리" 값을 그대로 "다음 주 예측값"으로 사용해요.
#       (아무 것도 학습하지 않고 그냥 베끼는 거예요)

print("① 나이브 모형 예측 완료! (이번 주 값을 그대로 다음 주 값으로 사용)")
# 위 줄: 완료 메시지예요.


# %%
# ------------------------------------------------------------
# [셀 8] ② 선형회귀(Linear Regression) 모형
# ------------------------------------------------------------
# 입력변수들과 목표변수 사이에 "직선적인" 관계가 있다고 가정하고 학습해요.

linear_model = LinearRegression()
# 위 줄: 선형회귀 모형을 만들어요.

linear_model.fit(X_train, y_train)
# 위 줄: 학습용 데이터로 직선 관계(계수)를 찾아내요.

y_pred_linear = linear_model.predict(X_test)
# 위 줄: 시험용 데이터에 대해 다음 주 회사채금리를 예측해요.

print("② 선형회귀 모형 학습 및 예측 완료!")
# 위 줄: 완료 메시지예요.


# %%
# ------------------------------------------------------------
# [셀 9] ③ 랜덤포레스트(Random Forest) 모형
# ------------------------------------------------------------
# 여러 그루의 나무(의사결정나무)가 투표해서 예측하는 "숲" 모형이에요.

rf_model = RandomForestRegressor(n_estimators=200, random_state=42)
# 위 줄: 나무 200그루로 이루어진 랜덤포레스트 모형을 만들어요.

rf_model.fit(X_train, y_train)
# 위 줄: 학습용 데이터로 AI를 공부시켜요.

y_pred_rf = rf_model.predict(X_test)
# 위 줄: 시험용 데이터에 대해 다음 주 회사채금리를 예측해요.

print("③ 랜덤포레스트 모형 학습 및 예측 완료!")
# 위 줄: 완료 메시지예요.


# %%
# ------------------------------------------------------------
# [셀 10] ④ XGBoost 모형
# ------------------------------------------------------------
# 나무를 한 번에 다 심는 랜덤포레스트와 달리, 나무를 한 그루씩 순서대로 심으면서
# "직전 나무가 틀렸던 부분"을 다음 나무가 집중적으로 보완해가는 방식이에요.

xgb_model = XGBRegressor(n_estimators=200, learning_rate=0.05,
                            max_depth=3, random_state=42)
# 위 줄: XGBoost 모형을 만들어요. (나무 200그루, 학습률 0.05, 나무 깊이 3)

xgb_model.fit(X_train, y_train)
# 위 줄: 학습용 데이터로 AI를 공부시켜요.

y_pred_xgb = xgb_model.predict(X_test)
# 위 줄: 시험용 데이터에 대해 다음 주 회사채금리를 예측해요.

print("④ XGBoost 모형 학습 및 예측 완료!")
# 위 줄: 완료 메시지예요.


# %%
# ------------------------------------------------------------
# [셀 11] 4개 모형 성적표 비교하기 (MAE, R²)
# ------------------------------------------------------------

results = {
    '① 나이브': y_pred_naive,
    '② 선형회귀': y_pred_linear,
    '③ 랜덤포레스트': y_pred_rf,
    '④ XGBoost': y_pred_xgb,
}
# 위 줄: 4개 모형의 이름과 예측 결과를 하나로 묶어서 정리해요.

score_table = []
# 위 줄: 성적표를 담을 빈 리스트를 만들어요.

for name, y_pred in results.items():
    # 위 줄: 4개 모형을 하나씩 돌면서 성적을 계산해요.

    mae = mean_absolute_error(y_test, y_pred)
    # 위 줄: 이 모형의 MAE(평균적으로 몇 %p 틀렸는지)를 계산해요.

    r2 = r2_score(y_test, y_pred)
    # 위 줄: 이 모형의 R²(설명력)를 계산해요.

    score_table.append({'모형': name, 'MAE': mae, 'R2': r2})
    # 위 줄: 계산한 성적을 성적표 리스트에 추가해요.

score_df = pd.DataFrame(score_table)
# 위 줄: 리스트를 보기 좋은 표(데이터프레임)로 바꿔요.

print("=== 4개 모형 성적표 ===")
# 위 줄: 안내 메시지예요.

print(score_df.to_string(index=False))
# 위 줄: 성적표를 출력해요. (MAE는 작을수록, R²는 1에 가까울수록 좋아요)

print("\n[해석 팁] 만약 ②~④번 모형이 ①나이브 모형보다 MAE가 크다면(더 못 맞히면),")
print("그 AI 모형은 '그냥 베끼는 것'보다도 못하다는 뜻이니 다시 점검해봐야 해요!")
# 위 2줄: 나이브 모형이 왜 기준선 역할을 하는지 다시 한 번 짚어줘요.


# %%
# ------------------------------------------------------------
# [셀 12] 그림 1: 실제값 vs 4개 모형 예측값 (꺾은선 그래프)
# ------------------------------------------------------------

plt.figure(figsize=(14, 7))
# 위 줄: 그래프 도화지 크기를 정해요.

test_index = range(len(y_test))
# 위 줄: 시험 데이터의 순서를 가로축 숫자로 만들어요.

plt.plot(test_index, y_test.values, label='실제 다음주 회사채금리',
          color='black', linewidth=2.5)
# 위 줄: 실제 값을 검은 굵은 선으로 그려요. (정답)

plt.plot(test_index, y_pred_naive, label='① 나이브', color='gray',
          linestyle=':', linewidth=1.5)
# 위 줄: 나이브 모형의 예측을 회색 점선으로 그려요.

plt.plot(test_index, y_pred_linear, label='② 선형회귀', color='blue',
          linestyle='--', linewidth=1.5)
# 위 줄: 선형회귀 모형의 예측을 파란 점선으로 그려요.

plt.plot(test_index, y_pred_rf, label='③ 랜덤포레스트', color='orange',
          linestyle='-.', linewidth=1.5)
# 위 줄: 랜덤포레스트 모형의 예측을 주황 점선으로 그려요.

plt.plot(test_index, y_pred_xgb, label='④ XGBoost', color='red',
          linestyle='--', linewidth=1.5)
# 위 줄: XGBoost 모형의 예측을 빨간 점선으로 그려요.

plt.title('4개 모형의 다음 주 회사채금리 예측 비교')
# 위 줄: 그래프 제목을 붙여요.

plt.xlabel('시험 데이터 순서 (시간 흐름)')
# 위 줄: 가로축 이름을 붙여요.

plt.ylabel('회사채금리(%)')
# 위 줄: 세로축 이름을 붙여요.

plt.legend()
# 위 줄: 각 선이 어떤 모형인지 설명을 붙여요.

plt.grid(alpha=0.3)
