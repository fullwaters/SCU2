# [셀 13] 그림 2: 모형별 MAE 비교 (막대그래프)
# ------------------------------------------------------------

plt.figure(figsize=(9, 6))
# 위 줄: 그래프 도화지 크기를 정해요.

colors = ['gray', 'blue', 'orange', 'red']
# 위 줄: 4개 모형의 막대 색깔을 각각 정해요. (위 꺾은선 그래프와 색을 맞춰요)

bars = plt.bar(score_df['모형'], score_df['MAE'], color=colors)
# 위 줄: 모형별 MAE를 막대그래프로 그려요. (막대가 낮을수록 잘 맞힌 모형이에요)

for bar, mae_value in zip(bars, score_df['MAE']):
    # 위 줄: 막대 위에 정확한 숫자를 적어주기 위해, 막대를 하나씩 확인해요.

    plt.text(bar.get_x() + bar.get_width()/2, bar.get_height(),
               f'{mae_value:.4f}', ha='center', va='bottom', fontweight='bold')
    # 위 줄: 각 막대 바로 위에 MAE 숫자를 표시해줘요.

plt.title('모형별 MAE 비교 (낮을수록 잘 맞히는 모형)')
# 위 줄: 그래프 제목을 붙여요.

plt.xlabel('모형')
# 위 줄: 가로축 이름을 붙여요.

plt.ylabel('MAE (평균 절대 오차, %p)')
# 위 줄: 세로축 이름을 붙여요.

plt.axhline(score_df.loc[score_df['모형'] == '① 나이브', 'MAE'].values[0],
             color='black', linestyle='--', alpha=0.6)
# 위 줄: 나이브 모형의 MAE 위치에 검은 점선을 그어서, "이 선 아래로 내려가야
#       나이브보다 나은 모형"이라는 기준선을 보여줘요.

plt.tight_layout()
# 위 줄: 그래프 요소들이 겹치지 않게 간격을 맞춰요.

plt.show()
